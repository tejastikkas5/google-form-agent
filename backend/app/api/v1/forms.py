# Endpoints
# ======================================================================

@router.post(
    "/generate-schema",
    response_model=FormSchema,
    summary="Generate Form Schema from Prompt",
    description="Converts natural language description into a validated, structured FormSchema JSON.",
)
async def generate_form_schema(
    payload: GenerateSchemaRequest,
    provider: str | None = None,
) -> FormSchema:
    """
    Convert prompt into a validated FormSchema JSON object.
    Does NOT call Google Forms API or create external forms.
    """
    if not payload.prompt or not payload.prompt.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Prompt text cannot be empty.",
        )

    try:
        provider_instance = get_llm_provider(provider_name=provider)
        form_schema = await provider_instance.generate_form_schema(payload.prompt)
        return form_schema
    except LLMError as exc:
        raise HTTPException(status_code=exc.status_code, detail=exc.message)
    except Exception as exc:
        logger.exception("Unexpected error generating form schema: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate form schema: {str(exc)}",
        )


@router.post(
    "/prompt-generate",
    response_model=PromptGenerateResponse,
    summary="AI Prompt → Create Full Google Form",
    description=(
        "Takes a natural language prompt, uses AI to design the complete form schema, "
        "then creates a real Google Form in the user's Google account with all questions populated. "
        "This is the main AI-powered form creation endpoint."
    ),
)
async def prompt_generate_form(
    payload: PromptGenerateRequest,
    session_token: str | None = Cookie(default=None),
    authorization: str | None = Header(default=None),
) -> PromptGenerateResponse:
    """
    Full pipeline: prompt → AI schema → create Google Form with all questions.
    """
    if not payload.prompt or not payload.prompt.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Prompt text cannot be empty.",
        )

    # Step 1: Validate auth
    access_token = _extract_access_token(session_token, authorization)

    # Step 2: Generate FormSchema from AI
    try:
        provider_instance = get_llm_provider(provider_name=payload.provider)
        form_schema = await provider_instance.generate_form_schema(
            payload.prompt, current_schema=payload.current_schema
        )
    except LLMError as exc:
        raise HTTPException(status_code=exc.status_code, detail=exc.message)
    except Exception as exc:
        logger.exception("Unexpected error generating form schema from prompt: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"AI failed to generate form schema: {str(exc)}",
        )

    # Step 3: Create or update Google Form
    try:
        if payload.current_form_id:
            result = await google_forms_service.update_form_from_schema(
                access_token=access_token,
                form_id=payload.current_form_id,
                form_schema=form_schema,
            )
        else:
            result = await google_forms_service.create_form_from_schema(
                access_token=access_token,
                form_schema=form_schema,
            )
    except GoogleFormsError as exc:
        raise HTTPException(status_code=exc.status_code, detail=exc.message)
    except Exception as exc:
        logger.exception("Unexpected error processing Google Form from schema: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Internal server error while processing Google Form.",
        )

    return PromptGenerateResponse(
        formId=result["formId"],
        title=result["title"],
        description=result.get("description", ""),
        editUrl=result["editUrl"],
        responderUrl=result["responderUrl"],
        createdTime=result["createdTime"],
        questionCount=result.get("questionCount", 0),
        form_schema=form_schema,
    )


@router.post(
    "/create",
    response_model=FormCreateResponse,
    summary="Create Blank Google Form",
    description="Creates a new blank Google Form in the authenticated user's Google Workspace account.",
)
async def create_form(
    payload: FormCreateRequest | None = None,
    session_token: str | None = Cookie(default=None),
    authorization: str | None = Header(default=None),
) -> FormCreateResponse:
    """
    Create a new blank Google Form.
    """
    access_token = _extract_access_token(session_token, authorization)
    title = payload.title if payload and payload.title else "Untitled Form"

    try:
        result = await google_forms_service.create_blank_form(access_token=access_token, title=title)
        return FormCreateResponse(**result)
    except GoogleFormsError as exc:
        raise HTTPException(status_code=exc.status_code, detail=exc.message)
    except Exception as exc:
        logger.exception("Unexpected error during Google Form creation: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Internal server error creating Google Form.",
        )


@router.get(
    "/{formId}",
    response_model=FormDetailsResponse,
    summary="Get Google Form Details",
    description="Retrieves metadata for an existing Google Form by ID.",
)
async def get_form(
    formId: str,
    session_token: str | None = Cookie(default=None),
    authorization: str | None = Header(default=None),
) -> FormDetailsResponse:
    """
    Get Google Form metadata.
    """
    access_token = _extract_access_token(session_token, authorization)
    try:
        result = await google_forms_service.get_form_details(access_token=access_token, form_id=formId)
        return FormDetailsResponse(**result)
    except GoogleFormsError as exc:
        raise HTTPException(status_code=exc.status_code, detail=exc.message)
    except Exception as exc:
        logger.exception("Unexpected error retrieving Google Form: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Internal server error retrieving Google Form details.",
        )
