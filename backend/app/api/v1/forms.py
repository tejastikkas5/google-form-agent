"""
app/api/v1/forms.py
===================
API router for Google Forms and Form Schema operations.

Routes:
  - POST /api/v1/forms/generate-schema      → LLM prompt → FormSchema JSON
  - POST /api/v1/forms/prompt-generate      → LLM prompt → creates real Google Form with questions
  - POST /api/v1/forms/create               → Create blank Google Form
  - GET  /api/v1/forms/{formId}             → Get Google Form metadata
"""

from __future__ import annotations

import logging

from fastapi import APIRouter, Cookie, Header, HTTPException, status
from pydantic import BaseModel, Field

from app.auth.service import google_auth_service
from app.forms.schemas import FormSchema
from app.google.forms import GoogleFormsError, google_forms_service
from app.llm.exceptions import LLMError
from app.llm.factory import get_llm_provider

logger = logging.getLogger(__name__)

router = APIRouter(prefix="", tags=["Google Forms"])


# ======================================================================
# Request / Response Schemas
# ======================================================================

class GenerateSchemaRequest(BaseModel):
    prompt: str = Field(..., min_length=1, description="Natural language prompt describing the form to create")


class PromptGenerateRequest(BaseModel):
    prompt: str = Field(..., min_length=1, description="Natural language prompt describing the Google Form to create or modify")
    provider: str | None = Field(default=None, description="LLM provider override (default: gemini)")
    current_form_id: str | None = Field(default=None, description="ID of existing Google Form to modify, if any")
    current_schema: FormSchema | None = Field(default=None, description="Current FormSchema if modifying an existing form")


class PromptGenerateResponse(BaseModel):
    formId: str = Field(..., description="Google Form unique identifier")
    title: str = Field(..., description="Form title generated by AI")
    description: str = Field(default="", description="Form description")
    editUrl: str = Field(..., description="Google Forms edit URL for form owner")
    responderUrl: str = Field(..., description="Public shareable URL for respondents")
    createdTime: str = Field(..., description="ISO 8601 creation timestamp")
    questionCount: int = Field(default=0, description="Number of questions added to the form")
    form_schema: FormSchema = Field(..., description="Generated form schema from AI")


class FormCreateRequest(BaseModel):
    title: str = Field(default="Untitled Form", description="Title for the new Google Form")


class FormCreateResponse(BaseModel):
    formId: str = Field(..., description="Google Form unique identifier")
    title: str = Field(..., description="Form title")
    editUrl: str = Field(..., description="Google Forms edit URL for form owner")
    responderUrl: str = Field(..., description="Public shareable URL for respondents")
    createdTime: str = Field(..., description="ISO 8601 creation timestamp")


class FormDetailsResponse(BaseModel):
    formId: str = Field(..., description="Google Form unique identifier")
    title: str = Field(..., description="Form title")
    description: str = Field("", description="Form description")
    revisionId: str = Field("", description="Form revision identifier")
    responderUrl: str = Field(..., description="Public shareable URL")
    editUrl: str = Field(..., description="Google Forms edit URL")


# ======================================================================
# Helpers
# ======================================================================

def _extract_access_token(session_token: str | None, authorization: str | None) -> str:
    token = session_token
    if not token and authorization and authorization.startswith("Bearer "):
        token = authorization.split("Bearer ", 1)[1].strip()

    if not token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required. Please sign in with Google.",
        )

    access_token = google_auth_service.get_access_token_from_session(token)
    if not access_token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Valid Google OAuth access token not found in session. Please sign in again.",
        )
    return access_token


